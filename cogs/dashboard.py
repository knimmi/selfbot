app = Flask(__name__)
# Volatile secret key: all sessions invalidate on bot restart
app.secret_key = os.urandom(24) 
app.config.update(
    SESSION_COOKIE_HTTPONLY=True,
    SESSION_COOKIE_SAMESITE='Lax',
)

# In-memory rate limiting to prevent brute force
limiter = Limiter(
    get_remote_address,
    app=app,
    default_limits=["200 per day", "50 per hour"],
    storage_uri="memory://"
)

bot_instance = None

