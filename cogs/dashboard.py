@app.route('/')
def index():
    if not session.get('logged_in'):
        return redirect('/login')
    return render_template_string(DASHBOARD_HTML)

@app.route('/login', methods=['GET', 'POST'])
@limiter.limit("5 per minute")
def login():
    if request.method == 'POST':
        user = request.form.get('username', '')
        pwd = request.form.get('password', '')
        
        stored_user = bot_instance.config.get('dash_username')
        stored_hash = bot_instance.config.get('dash_hash')
        
        if not stored_user or not stored_hash:
            return render_template_string(LOGIN_HTML, error="Dashboard credentials not configured.")
        
        if user == stored_user and check_password_hash(stored_hash, pwd):
            session['logged_in'] = True
            return redirect('/')
        else:
            return render_template_string(LOGIN_HTML, error="Authentication Failed.")
            
    return render_template_string(LOGIN_HTML)

@app.route('/logout')
def logout():
    session.clear()
    return redirect('/login')

@app.route('/callback')
def spotify_callback():
    """Captures the Spotify OAuth code natively without broken pages."""
    if not session.get('logged_in'):
        return redirect('/login')
        
    code = request.args.get('code')
    if code:
        return f"""
        <body style="background-color:#2f3136; color:white; font-family:sans-serif; text-align:center; padding-top:50px;">
            <h3 style="color:#57F287;">Spotify Authorized!</h3>
            <p>Copy the URL below and run it in Discord to complete setup:</p>
            <code style="background:#202225; padding:10px; border-radius:5px; display:inline-block; margin-top:10px;">.spauth {request.url}</code>
            <br><br><a href="/" style="color:#5865F2;">Return to Dashboard</a>
        </body>
        """
    return redirect('/')

def run_app():
    app.run(host='0.0.0.0', port=8080, debug=False, use_reloader=False)

class Dashboard(commands.Cog):
    def __init__(self, bot):
        self.bot = bot
        global bot_instance
        bot_instance = bot
        
        # Hash the raw password generated by install.sh to prevent plaintext exposure
        raw_hash = self.bot.config.get("dash_hash", "")
        if raw_hash.startswith("raw:"):
            self.bot.config["dash_hash"] = generate_password_hash(raw_hash[4:])
            with open("config.json", "w", encoding="utf-8") as f:
                json.dump(self.bot.config, f, indent=4)
        
        self.server_thread = threading.Thread(target=run_app, daemon=True)
        self.server_thread.start()

async def setup(bot):
    await bot.add_cog(Dashboard(bot))